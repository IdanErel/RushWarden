import type { RunRecord } from './runner.js';

/**
 * The balance report (GDD §11), as Markdown with a stable layout: the same records always give
 * byte-identical output, so a nightly diff shows only real changes. No wall-clock time in it.
 */

export interface ReportMeta {
  readonly district: number;
  readonly rounds: number;
  readonly seeds: number;
  readonly bots: readonly string[];
  readonly commit: string;
  /** Lines shown in a warning box at the top (stand-in data, stub sim). */
  readonly warnings: readonly string[];
}

const pct = (num: number, den: number): string =>
  den === 0 ? 'n/a' : `${(Math.round((num * 1000) / den) / 10).toFixed(1)}%`;
const signedPts = (permille: number): string =>
  `${permille >= 0 ? '+' : '−'}${(Math.abs(permille) / 10).toFixed(1)}`;
const rate = (wins: number, n: number): number => (n === 0 ? 0 : Math.round((wins * 1000) / n));

function median(xs: readonly number[]): number {
  if (xs.length === 0) return 0;
  const s = xs.slice().sort((a, b) => a - b);
  return s[(s.length - 1) >> 1] ?? 0;
}

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

const TAGS_OF = /^archetype\((\w+)\)$/;

/** Gate criterion 2 (§13, ADR-010 point 2): every archetype bot within 35–65% inclusive. */
export function gateCriterion2(
  records: readonly RunRecord[],
  bots: readonly string[],
): { tag: string; runs: number; winPermille: number; pass: boolean }[] {
  return bots
    .filter((b) => TAGS_OF.test(b))
    .map((b) => {
      const rs = records.filter((r) => r.bot === b);
      const w = rate(rs.filter((r) => r.win).length, rs.length);
      return {
        tag: TAGS_OF.exec(b)?.[1] ?? b,
        runs: rs.length,
        winPermille: w,
        pass: w >= 350 && w <= 650,
      };
    });
}

export function renderReport(
  records: readonly RunRecord[],
  meta: ReportMeta,
  cardTags: ReadonlyMap<string, readonly string[]>,
): string {
  const out: string[] = [];
  out.push('# Balance report');
  out.push('');
  out.push(
    `District ${meta.district} · ${meta.rounds}-round runs · seeds 1–${meta.seeds} per bot · ${records.length} runs · commit \`${meta.commit}\``,
  );
  out.push('');
  out.push(
    'Generated by `pnpm --filter @rushwarden/balance run report` (GDD §11, P1-BAL-02, ADR-019). Same inputs give a byte-identical file.',
  );
  if (meta.warnings.length) {
    out.push('');
    out.push('> [!WARNING]');
    for (const w of meta.warnings) out.push(`> - ${w}`);
  }

  // Gate criterion 2.
  const gate = gateCriterion2(records, meta.bots);
  out.push('', '## Gate criterion 2: archetype win rates (35–65%)', '');
  out.push(
    table(
      ['Archetype', 'Runs', 'Win rate', 'In 35–65%'],
      gate.map((g) => [g.tag, String(g.runs), pct(g.winPermille, 1000), g.pass ? 'yes' : 'no']),
    ),
  );
  const passing = gate.filter((g) => g.pass).length;
  out.push(
    '',
    `**${passing} of ${gate.length} archetypes in range.** The criterion needs all five (ADR-010 point 2).`,
  );

  // Win rate per bot.
  out.push('', '## Win rate per bot', '');
  out.push(
    table(
      [
        'Bot',
        'District',
        'Mayor',
        'Runs',
        'Wins',
        'Win rate',
        'Median rounds',
        'Median watch time',
      ],
      meta.bots.map((b) => {
        const rs = records.filter((r) => r.bot === b);
        const wins = rs.filter((r) => r.win).length;
        const secs = median(rs.map((r) => Math.round(r.ticks / 20)));
        return [
          b,
          String(meta.district),
          rs[0]?.mayor ?? 'n/a',
          String(rs.length),
          String(wins),
          pct(wins, rs.length),
          String(median(rs.map((r) => r.rounds))),
          `${Math.floor(secs / 60)}:${String(secs % 60).padStart(2, '0')}`,
        ];
      }),
    ),
  );
  out.push(
    '',
    "Watch time is simulated Go-phase time at 1× only; §11's 10–15 minute run length also includes placement time, measured with players.",
  );

  // Drafted win-rate delta per card.
  const baseWins = records.filter((r) => r.win).length;
  const base = rate(baseWins, records.length);
  const cards = [...cardTags.keys()].sort();
  out.push('', '## Cards: drafted win-rate delta and pick rate', '');
  out.push(
    `Baseline win rate over all runs: ${pct(baseWins, records.length)}. Delta = win rate of runs that drafted the card minus the baseline; §11 limits: +12 / −8 points.`,
    '',
  );
  out.push(
    table(
      [
        'Card',
        'Tags',
        'Offered',
        'Picked',
        'Pick rate',
        'Runs drafting',
        'Win rate drafted',
        'Delta (pts)',
        'Within limits',
      ],
      cards.map((id) => {
        const offered = records.reduce((n, r) => n + r.offered.filter((x) => x === id).length, 0);
        const picked = records.reduce((n, r) => n + r.drafted.filter((x) => x === id).length, 0);
        const drafting = records.filter((r) => r.drafted.includes(id));
        const w = drafting.filter((r) => r.win).length;
        const delta = drafting.length ? rate(w, drafting.length) - base : 0;
        return [
          id,
          (cardTags.get(id) ?? []).join('/'),
          String(offered),
          String(picked),
          pct(picked, offered),
          String(drafting.length),
          pct(w, drafting.length),
          drafting.length ? signedPts(delta) : 'n/a',
          drafting.length ? (delta <= 120 && delta >= -80 ? 'yes' : 'no') : 'n/a',
        ];
      }),
    ),
  );

  // Archetype purity vs win rate.
  const buckets = [
    ['< 40%', 0, 400],
    ['40–59%', 400, 600],
    ['60–79%', 600, 800],
    ['≥ 80%', 800, 1001],
  ] as const;
  const purity = (r: RunRecord): number => {
    const counts = new Map<string, number>();
    for (const id of r.deck)
      for (const t of cardTags.get(id) ?? []) counts.set(t, (counts.get(t) ?? 0) + 1);
    const top = Math.max(0, ...counts.values());
    return r.deck.length ? Math.round((top * 1000) / r.deck.length) : 0;
  };
  out.push(
    '',
    '## Archetype purity vs win rate',
    '',
    "Purity = share of final-deck cards carrying the deck's most common tag.",
    '',
  );
  out.push(
    table(
      ['Purity', 'Runs', 'Win rate'],
      buckets.map(([label, lo, hi]) => {
        const rs = records.filter((r) => purity(r) >= lo && purity(r) < hi);
        return [label, String(rs.length), pct(rs.filter((r) => r.win).length, rs.length)];
      }),
    ),
  );

  // Round of death.
  const maxRound = Math.max(0, ...records.map((r) => r.rounds));
  out.push('', '## Round-of-death histogram (lost runs)', '');
  out.push(
    table(
      ['Round', ...meta.bots],
      Array.from({ length: maxRound }, (_, i) => [
        String(i + 1),
        ...meta.bots.map((b) =>
          String(records.filter((r) => r.bot === b && !r.win && r.rounds === i + 1).length),
        ),
      ]),
    ),
  );

  // Gridlock frequency.
  out.push('', '## Gridlock frequency', '');
  out.push(
    table(
      ['Bot', 'Rounds played', 'Gridlocked rounds', 'Rate'],
      meta.bots.map((b) => {
        const rs = records.filter((r) => r.bot === b);
        const rounds = rs.reduce((n, r) => n + r.rounds, 0);
        const g = rs.reduce((n, r) => n + r.gridlockRounds, 0);
        return [b, String(rounds), String(g), pct(g, rounds)];
      }),
    ),
  );

  // Top 20 decks.
  const decks = new Map<string, { runs: number; wins: number }>();
  for (const r of records) {
    const key = summarizeDeck(r.deck);
    const d = decks.get(key) ?? { runs: 0, wins: 0 };
    d.runs++;
    if (r.win) d.wins++;
    decks.set(key, d);
  }
  const top = [...decks.entries()]
    .sort((a, b) => b[1].wins - a[1].wins || b[1].runs - a[1].runs || (a[0] < b[0] ? -1 : 1))
    .slice(0, 20);
  out.push('', '## Top 20 decks (by wins)', '');
  out.push(
    table(
      ['#', 'Deck', 'Runs', 'Wins', 'Share of runs'],
      top.map(([k, d], i) => [
        String(i + 1),
        k,
        String(d.runs),
        String(d.wins),
        pct(d.runs, records.length),
      ]),
    ),
  );
  out.push('');
  return out.join('\n');
}

/** "2× one-way, 1× recount, …" in id order. */
export function summarizeDeck(deck: readonly string[]): string {
  const counts = new Map<string, number>();
  for (const id of deck) counts.set(id, (counts.get(id) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => (a[0] < b[0] ? -1 : 1))
    .map(([id, n]) => `${n}× ${id}`)
    .join(', ');
}
